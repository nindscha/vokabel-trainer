-- Baseline: Vokabel-Tabellen vor der Familien-Migration (0002).
-- Idempotent: kann auf einer bestehenden Datenbank erneut laufen.
-- Die Vokabeln selbst kommen aus sql/seed_words.sql.

create table if not exists public.words (
  id         bigint generated by default as identity primary key,
  week       integer not null,
  en         text not null,
  de         text not null,
  created_at timestamptz default now()
);

create table if not exists public.progress (
  id             bigint generated by default as identity primary key,
  child_name     text not null default 'Kind',
  week           integer not null,
  word_en        text not null,
  correct        integer default 0,
  wrong          integer default 0,
  last_practiced date default current_date,
  constraint progress_child_name_week_word_en_key unique (child_name, week, word_en)
);

alter table public.words    enable row level security;
alter table public.progress enable row level security;

drop policy if exists "Allow public read access to words" on public.words;
create policy "Allow public read access to words"
  on public.words for select
  to public
  using (true);
